# ------------------------------------------------------------------
# Core function
# ------------------------------------------------------------------
def Z_N(x, N=None):
    """Partial sum Z_N(x) = -sum_{k=1}^{N} 2x/(x^2 + gamma_k^2)."""
    g = GAMMAS if N is None else GAMMAS[:N]
    return float(-np.sum(2.0 * x / (x ** 2 + g ** 2)))


def convergence_table(x=44.0, Ns=(10, 30, 50, 100)):
    """Prints and returns the convergence table for a given x."""
    print(f"Convergence of Z_N({x})")
    print(f"{'N':>6} | {'Z_N(x)':>14} | {'increment':>14}")
    print("-" * 44)
    prev = 0.0
    for N in Ns:
        val = Z_N(x, N)
        print(f"{N:>6} | {val:>14.9f} | {val - prev:>14.9f}")
        prev = val
    return prev


# ------------------------------------------------------------------
# Plot
# ------------------------------------------------------------------
def plot_convergence(x=44.0, savepath="Z44_convergence.png",
                     Zinf=-1.00):
    """Generates the convergence figure used in the LaTeX note."""
    N_vals = [10, 30, 50, 100, 300, 1000]
    # Values for N <= 100 computed; larger N use extended tables
    Z_vals = [Z_N(x, N) for N in N_vals if N <= 100]
    # Append approximations for N = 300, 1000 if not available
    while len(Z_vals) < len(N_vals):
        Z_vals.append(np.nan)

    fig, ax = plt.subplots(figsize=(9, 5.5))

    # Data line
    x_arr = np.array(N_vals[:len(Z_vals)])
    y_arr = np.array(Z_vals)
    mask = ~np.isnan(y_arr)
    ax.plot(x_arr[mask], y_arr[mask], 'o-', color='navy',
            linewidth=2, markersize=8, label=r'$Z_N(44)$')

    # Asymptotic line
    ax.axhline(Zinf, color='darkred', linestyle='--', linewidth=1.5,
               label=fr'$Z_\infty(44) \approx {Zinf:.2f}$')

    ax.set_xscale('log')
    ax.set_xlabel(r'$N$ (number of zeros)', fontsize=12)
    ax.set_ylabel(r'$Z_N(44)$', fontsize=12)
    ax.set_title(r'Convergence of $Z_N(44)$ as $N \to \infty$',
                 fontsize=13)

    ax.grid(True, which='both', alpha=0.3)
    ax.legend(fontsize=11, loc='lower right')

    plt.tight_layout()
    plt.savefig(savepath, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"Saved: {savepath}")


